export function coordinates(id) {
  if (id <= 7) return { row: 8, col: 8 - id };
  if (id <= 14) return { row: 15 - id, col: 1 };
  if (id <= 21) return { row: 1, col: id - 13 };
  return { row: id - 20, col: 8 };
}
